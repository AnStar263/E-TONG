/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_DMA_Init();
  MX_SPI1_Init();
  MX_TIM1_Init();
  MX_USART1_UART_Init();
  MX_DCMI_Init();
  MX_DAC_Init();
  /* USER CODE BEGIN 2 */
  st7789_init();
  page_console();
  
  console_print("TEST#1");
  st7789_display_on();
  HAL_UART_Receive_IT(&huart1, &rx_data, 1);
  HAL_TIM_PWM_Start(&htim1, TIM_CHANNEL_1);
  
  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  static uint32_t last_frame_tick = 0;

  while(1) {
    /* 1. 安全切页检查：在主循环主线程中有序执行，绝不与 SPI 冲突 */
    if (page_change_flag) {
      page_change_flag = 0;

      switch (next_page_req) {
        case PAGE_CONSOLE:
          page_console();
          break;
        case PAGE_WAVE:
          // 切回波形页前，必须清空历史旧帧坐标缓存，防止对比错误
          memset(g_last_wave, 0, sizeof(g_last_wave));
          page_wave();
          break;
        case PAGE_PARAM:
          page_param();
          break;
      }
    }

    /* 2. 状态机调度 */
    switch (current_state) {
      case Init:
        if (HAL_GetTick() - last_frame_tick >= 33) {
          last_frame_tick = HAL_GetTick();

          HAL_GPIO_WritePin(GPIOB, GPIO_PIN_9, GPIO_PIN_SET);
          HAL_DCMI_Start_DMA(&hdcmi, DCMI_MODE_SNAPSHOT, (uint32_t)adc_buf, 512);

          HAL_GPIO_WritePin(GPIOB, GPIO_PIN_9, GPIO_PIN_RESET);
          for(volatile int i = 0; i < 2000; i++); 
          HAL_GPIO_WritePin(GPIOB, GPIO_PIN_9, GPIO_PIN_SET);

          current_state = Measure;
        }
        break;

      case Measure:
        if (HAL_DCMI_GetState(&hdcmi) == HAL_DCMI_STATE_READY) {
          HAL_GPIO_WritePin(GPIOB, GPIO_PIN_9, GPIO_PIN_SET);
          current_state = Process;
        }
        else if (HAL_DCMI_GetState(&hdcmi) == HAL_DCMI_STATE_ERROR) {
          HAL_DCMI_Stop(&hdcmi);
          HAL_GPIO_WritePin(GPIOB, GPIO_PIN_9, GPIO_PIN_SET);
          current_state = Init;
        }
        break;

      case Process:
        // 核心保护：只有当前确认是波形页才绘制波形
        if (current_page == PAGE_WAVE && !page_change_flag) {
          for (int i = 0; i < 320; i++) {
            int32_t delta = (int32_t)adc_buf[i] - 2048;
            int32_t y = 132 - (delta * 100 / 2048);
            if (y < 25)  y = 25;
            if (y > 239) y = 239;
            g_curr_wave[i] = (uint8_t)y;
          }

          screen_draw_frame(g_last_wave, g_curr_wave, 320);
        }

        current_state = Init;
        break;
    }
  }
  /* USER CODE END WHILE */
  /* USER CODE BEGIN 3 */

  /* USER CODE END 3 */
}

